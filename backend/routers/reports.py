@router.get("/child/{child_id}/summary")
async def get_child_summary(
    child_id: int,
    days: int = 30,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Get a quick summary of child's recent allergy data for report generation preview.
    """
    try:
        # Verify child belongs to current user
        child = db.query(Child).filter(
            Child.id == child_id,
            Child.parent_id == current_user.id
        ).first()
        
        if not child:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Child not found or access denied"
            )
        
        # Get recent data
        end_date = datetime.utcnow()
        start_date = end_date - timedelta(days=days)
        
        daily_logs = db.query(DailyLog).filter(
            DailyLog.child_id == child_id,
            DailyLog.date >= start_date,
            DailyLog.date <= end_date
        ).all()
        
        # Calculate summary statistics
        total_logs = len(daily_logs)
        
        # Count symptoms and triggers
        all_symptoms = []
        all_triggers = []
        severe_reactions = 0
        
        for log in daily_logs:
            if log.symptoms:
                if isinstance(log.symptoms, str):
                    symptoms = json.loads(log.symptoms) if log.symptoms else []
                else:
                    symptoms = log.symptoms or []
                all_symptoms.extend(symptoms)
            
            if log.triggers:
                if isinstance(log.triggers, str):
                    triggers = json.loads(log.triggers) if log.triggers else []
                else:
                    triggers = log.triggers or []
                all_triggers.extend(triggers)
            
            # Check for severe reactions (simplified logic)
            if (log.eczema_severity in ['severe', 'very_severe'] or 
                log.asthma_severity in ['severe', 'very_severe'] or
                log.allergic_reaction_severity in ['severe', 'very_severe']):
                severe_reactions += 1
        
        # Count unique items
        unique_symptoms = list(set(all_symptoms))
        unique_triggers = list(set(all_triggers))
        
        return {
            "child_name": child.name,
            "summary_period_days": days,
            "total_log_entries": total_logs,
            "unique_symptoms": unique_symptoms,
            "unique_triggers": unique_triggers,
            "severe_reactions_count": severe_reactions,
            "known_allergies": json.loads(child.known_allergies) if child.known_allergies else [],
            "current_medications": json.loads(child.medications) if child.medications else [],
            "medical_conditions": json.loads(child.medical_conditions) if child.medical_conditions else []
        }
        
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to get child summary: {str(e)}"
        )

