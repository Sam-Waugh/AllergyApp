@router.post("/generate", response_model=ReportResponse)
async def generate_allergy_report(
    request: ReportGenerationRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Generate a comprehensive allergy report using OpenAI API.
    
    The report includes:
    - Patient details and medical history
    - Reaction history with serious reactions prioritized
    - Allergy testing information
    - Diagnosed and suspected allergies
    - Current management plan
    - Planned appointments
    """
    try:
        # Verify child belongs to current user
        child = db.query(Child).filter(
            Child.id == request.child_id,
            Child.parent_id == current_user.id
        ).first()
        
        if not child:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Child not found or access denied"
            )
        
        # Get date range for data collection
        end_date = request.end_date or datetime.utcnow()
        start_date = request.start_date or (end_date - timedelta(days=90))  # Default to 3 months
        
        # Collect comprehensive data
        daily_logs = db.query(DailyLog).filter(
            DailyLog.child_id == request.child_id,
            DailyLog.date >= start_date,
            DailyLog.date <= end_date
        ).order_by(DailyLog.date.desc()).all()
        
        photos = []
        if request.include_photos:
            photos = db.query(PhotoEntry).filter(
                PhotoEntry.child_id == request.child_id,
                PhotoEntry.date >= start_date,
                PhotoEntry.date <= end_date
            ).order_by(PhotoEntry.date.desc()).all()
        
        # Initialize Hybrid AI report generator (combines AI insights with personal data)
        hybrid_service = HybridAIReportGenerator()
        
        # Generate the hybrid report (AI insights + complete personal data)
        report = await hybrid_service.generate_hybrid_report(
            child=child,
            parent=current_user,
            daily_logs=daily_logs,
            photos=photos,
            request=request
        )
        
        return ReportResponse(
            success=True,
            report_text=json.dumps(report, indent=2, default=str)  # Convert dict to JSON string
        )
        
    except Exception as e:
        import traceback
        error_details = f"Failed to generate report: {str(e)}\n\nTraceback:\n{traceback.format_exc()}"
        print(f"❌ Report generation error: {error_details}")
        return ReportResponse(
            success=False,
            error_message=error_details
        )

